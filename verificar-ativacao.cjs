'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {configurarAtivacao}=require('./controle-ativacao.cjs');
const {criarProcessador}=require('./processador.cjs');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE entregas(hash TEXT PRIMARY KEY, recebida_em TEXT NOT NULL, corpo TEXT NOT NULL, processada INTEGER NOT NULL DEFAULT 0)');
const cfg={conta:'100',publicacao:'200',mensagem:'Teste',ativacaoApos:'',regraAtiva:true,envioAtivo:false,token:''};
const processador=criarProcessador(db,cfg,async()=>{throw Error('não deveria enviar')});
const add=db.prepare('INSERT INTO acoes(conta,comentario,mensagem,estado,criado_em,atualizado_em) VALUES(?,?,?,?,?,?)');
add.run('100','1','Teste','pendente','2026-01-01','2026-01-01');
add.run('999','2','Teste','pendente','2026-01-01','2026-01-01');
assert.equal(configurarAtivacao(db,{ativo:false,conta:'100'}),null);
const primeira='2026-11-11T19:00:00.000Z',segunda='2026-11-11T20:00:00.000Z';
assert.equal(configurarAtivacao(db,{ativo:true,conta:'100',agora:()=>primeira}),primeira);
assert.equal(db.prepare('SELECT estado FROM acoes WHERE comentario=?').get('1').estado,'ignorada_antes_ativacao');
assert.equal(db.prepare('SELECT estado FROM acoes WHERE comentario=?').get('2').estado,'pendente');
assert.equal(configurarAtivacao(db,{ativo:true,conta:'100',agora:()=>segunda}),primeira);
configurarAtivacao(db,{ativo:false,conta:'100'});
assert.equal(configurarAtivacao(db,{ativo:true,conta:'100',agora:()=>segunda}),segunda);
const evento=JSON.stringify({object:'instagram',entry:[{id:'100',changes:[{field:'comments',value:{id:'3',text:'quero',from:{id:'900'},media:{id:'200'}}}]}]});
db.prepare('INSERT INTO entregas(hash,recebida_em,corpo) VALUES(?,?,?)').run('igual',segunda,evento);
cfg.ativacaoApos=segunda;assert.equal(processador.planejarPendentes(),0);
db.close();console.log('Ativação: apenas novos, manutenção após reinício, pausa, reativação e isolamento verificados.');
